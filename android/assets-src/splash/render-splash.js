// Brand splash (재개픽, brand v7): full-screen navy + white "Pick" mark (house with yellow door, yellow check badge),
// no wordmark. Geometry: ../brand-mark.js (generated from brand_v7/src/pick.py, same as the launcher / Play icon).
// One vector drawable is used for both stages so they look identical:
//   - Android 12+ system splash: values-v31/themes.xml windowSplashScreenAnimatedIcon (240dp icon with icon
//     background = navy, so the mark must sit inside the 160dp mask circle — checked below)
//   - androidbrowserhelper TWA splash: SPLASH_IMAGE_DRAWABLE (rasterised at its 240dp intrinsic size, ScaleType
//     CENTER, both in LauncherActivity and in Chrome's splash), background @color/backgroundColor.
// The check and the gap around the badge are holes, so the splash background (values / values-night) shows through.
//
// Writes <res>/drawable/splash.xml (default ../../app/src/main/res) and, with a 2nd argument, a preview PNG.
// Usage: NODE_PATH=$(npm root -g) node android/assets-src/splash/render-splash.js [resDir] [preview.png]
const fs = require('fs');
const path = require('path');
const M = require('../brand-mark');

const RES = path.resolve(process.argv[2] || path.join(__dirname, '../../app/src/main/res'));
const PREVIEW = process.argv[3];
const NAVY = M.NAVY, NAVY_NIGHT = M.NAVY_D, YELLOW = M.YELLOW;
const CANVAS = 240;            // dp, Android 12 icon-with-background size
const MASK_D = 160;            // dp, Android 12 icon mask circle
const MARK_W = 96;             // dp, mark width on screen

const BW = M.BOX.x1 - M.BOX.x0, BH = M.BOX.y1 - M.BOX.y0, BCX = (M.BOX.x0 + M.BOX.x1) / 2, BCY = (M.BOX.y0 + M.BOX.y1) / 2;
const K = MARK_W / Math.max(BW, BH);
const TX = +(CANVAS / 2 - BCX * K).toFixed(4), TY = +(CANVAS / 2 - BCY * K).toFixed(4), KS = +K.toFixed(5);
const reach = M.maxRadius(BCX, BCY) * K;
if (reach > MASK_D / 2 - 4) throw new Error(`splash mark reaches ${reach.toFixed(1)}dp, outside the ${MASK_D}dp mask`);

const XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets-src/splash/render-splash.js: 재개픽 splash mark (white house, yellow door, yellow check badge;
     check and badge gap are holes). ${CANVAS}dp canvas, mark ${MARK_W}dp wide, centred, farthest point ${reach.toFixed(1)}dp
     from the centre: inside the Android 12 ${MASK_D}dp icon circle.
     Used by values-v31 windowSplashScreenAnimatedIcon and by the TWA SPLASH_IMAGE_DRAWABLE. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${CANVAS}dp"
    android:height="${CANVAS}dp"
    android:viewportWidth="${CANVAS}"
    android:viewportHeight="${CANVAS}">
    <group android:translateX="${TX}" android:translateY="${TY}" android:scaleX="${KS}" android:scaleY="${KS}">
        <path android:fillColor="#FFFFFF" android:fillType="evenOdd" android:pathData="${M.BODY}" />
        <path android:fillColor="${YELLOW}" android:fillType="evenOdd" android:pathData="${M.DOOR}" />
        <path android:fillColor="${YELLOW}" android:fillType="evenOdd" android:pathData="${M.BADGE}" />
    </group>
</vector>
`;
fs.mkdirSync(path.join(RES, 'drawable'), { recursive: true });
fs.writeFileSync(path.join(RES, 'drawable/splash.xml'), XML);
for (const d of ['mdpi', 'hdpi', 'xhdpi', 'xxhdpi', 'xxxhdpi']) fs.rmSync(path.join(RES, 'drawable-' + d, 'splash.png'), { force: true });
console.log('wrote', path.join(RES, 'drawable/splash.xml'), `(reach ${reach.toFixed(1)}dp / mask ${MASK_D / 2}dp)`);

if (PREVIEW) preview(PREVIEW).catch((e) => { console.error(e); process.exit(1); });

// Preview: 412x915dp phones. Mark comes from the written XML (converted back to SVG).
async function preview(out) {
  const { chromium } = require('playwright');
  const xml = fs.readFileSync(path.join(RES, 'drawable/splash.xml'), 'utf8');
  const attr = (s, n) => (s.match(new RegExp('android:' + n + '="([^"]*)"')) || [])[1];
  const mark = (bg) => xml.replace(/<\?xml[^>]*>|<!--[\s\S]*?-->|<vector[^>]*>|<\/vector>/g, '')
    .replace(/<group([^>]*)>/g, (_, a) => `<g transform="translate(${attr(a, 'translateX') || 0} ${attr(a, 'translateY') || 0}) scale(${attr(a, 'scaleX') || 1} ${attr(a, 'scaleY') || 1})">`)
    .replace(/<\/group>/g, '</g>')
    .replace(/<path([^>]*)\/>/g, (_, a) => `<path d="${attr(a, 'pathData')}" fill="${attr(a, 'fillColor') || 'none'}" fill-rule="evenodd"/>`)
    .split('@color/backgroundColor').join(bg);
  const W = 412, H = 915, SB = 32, NB = 48;
  // navBg: the nav bar colour actually shown. The Android 12 system splash draws navy under it; in the TWA stage the
  // nav bar is the TWA navigation colour (#FFFFFF / #15181D) on API < 35 (fitted). Only Chrome's edge-to-edge
  // mode (Android 15+) shows the navy splash through a transparent bar.
  const bars = (navBg) => `<div style="position:absolute;left:0;right:0;top:0;height:${SB}px;display:flex;align-items:center;justify-content:space-between;padding:0 22px;color:#fff;font:600 14px system-ui">
      <span>12:06</span><span style="letter-spacing:3px">▾ ◢ ▮</span></div>
    <div style="position:absolute;left:0;right:0;bottom:0;height:${NB}px;background:${navBg || 'transparent'};display:flex;align-items:center;justify-content:space-around;color:${navBg === '#FFFFFF' ? '#3C4350' : '#fff'};opacity:.9;font:20px system-ui"><span>|||</span><span>◯</span><span>‹</span></div>`;
  const phone = (bg, kind, navBg) => {
    const mask = kind === 'a12'
      ? `<circle cx="120" cy="120" r="${MASK_D / 2}" fill="none" stroke="#FFFFFF" stroke-opacity=".45" stroke-width="1" stroke-dasharray="4 4"/>` : '';
    const clip = kind === 'a12' ? `<defs><clipPath id="c${bg.slice(1)}"><circle cx="120" cy="120" r="${MASK_D / 2}"/></clipPath></defs>` : '';
    return `<div style="position:relative;width:${W}px;height:${H}px;background:${bg};border-radius:28px;overflow:hidden;box-shadow:0 0 0 1px rgba(0,0,0,.15)">
      ${bars(navBg)}
      <svg width="${CANVAS}" height="${CANVAS}" viewBox="0 0 ${CANVAS} ${CANVAS}" style="position:absolute;left:${(W - CANVAS) / 2}px;top:${(H - CANVAS) / 2}px">
        ${clip}<g ${kind === 'a12' ? `clip-path="url(#c${bg.slice(1)})"` : ''}><rect width="240" height="240" fill="${bg}"/>${mark(bg)}</g>${mask}</svg></div>`;
  };
  const col = (title, sub, inner) => `<div><div style="font:700 15px system-ui;color:#191F28;margin:0 0 4px">${title}</div><div style="font:12px system-ui;color:#6B7684;margin:0 0 10px">${sub}</div>${inner}</div>`;
  const html = `<body style="margin:0;background:#E9EDF3"><div style="padding:24px 28px;display:flex;gap:24px">
    ${col('Light · Android 12+ system splash', `bg ${NAVY} · icon bg ${NAVY} · dashed = ${MASK_D}dp mask`, phone(NAVY, 'a12'))}
    ${col('Light · TWA splash (all API 24+)', `@drawable/splash on ${NAVY} · nav bar #FFFFFF below API 35`, phone(NAVY, 'twa', '#FFFFFF'))}
    ${col('Dark · Android 12+ system splash', `values-night ${NAVY_NIGHT}`, phone(NAVY_NIGHT, 'a12'))}
    ${col('Dark · TWA splash', `@drawable/splash on ${NAVY_NIGHT} · nav bar #15181D below API 35`, phone(NAVY_NIGHT, 'twa', '#15181D'))}
  </div><div style="padding:0 28px 22px;font:12px/1.6 system-ui;color:#4E5968">
    상태바: 스플래시 동안 TWA 상태바 색 ${NAVY} / ${NAVY_NIGHT} → 페이지 검증 뒤 사이트 theme-color(#FFFFFF / #15181D).
    내비바: Android 12+ 시스템 스플래시는 남색. TWA 단계는 API 35 미만에서 기존 TWA 내비바 색(#FFFFFF / #15181D, 그림대로)이고, Chrome이 edge-to-edge로 그리는 Android 15+에서만 남색 바탕이 비쳐 보입니다. 페이드 300ms.
    워드마크 없음(두 단계가 같은 모양이 되도록).</div></body>`;
  const exe = process.env.CHROME || ['/opt/pw-browsers/chromium-1194/chrome-linux/chrome'].find((p) => fs.existsSync(p));
  const br = await chromium.launch(exe ? { executablePath: exe, args: ['--no-sandbox'] } : { args: ['--no-sandbox'] });
  const page = await br.newPage({ viewport: { width: 4 * W + 3 * 24 + 56, height: H + 160 }, deviceScaleFactor: 1 });
  await page.setContent(html);
  await page.screenshot({ path: out, fullPage: true });
  await br.close();
  console.log('preview', out);
}
