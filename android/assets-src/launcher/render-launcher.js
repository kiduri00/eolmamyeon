// Launcher icon (adaptive + legacy) for the 집핀 TWA, matching the shipped Play icon (v5 tint variant:
// #F2F5FC background, navy pin + white house + yellow door/shadow from public/icon.svg, glyph = 76% of the
// visible icon height). Design note: brand_v2/app_kit/design_tokens.md §7.
//
// Writes into <res> (default: ../../app/src/main/res):
//   values/ic_launcher_background.xml          #F2F5FC
//   drawable/ic_launcher_foreground.xml        vector, 108dp canvas, glyph 54.8dp tall (inside the 66dp safe circle)
//   mipmap-{mdpi..xxxhdpi}/ic_launcher_monochrome.png   108dp, white pin with house knocked out (Android 13 themed
//                                              icons), geometry from assets-src/icon-monochrome.svg
//   mipmap-{mdpi..xxxhdpi}/ic_launcher.png, ic_launcher_round.png   48dp legacy (pre-Android 8), on #F2F5FC
//   mipmap-anydpi-v26/ic_launcher.xml, ic_launcher_round.xml       adaptive icon (bg + fg + monochrome)
// and removes the bubblewrap ic_maskable.png mipmaps (no longer referenced).
//
// Usage: NODE_PATH=$(npm root -g) node android/assets-src/launcher/render-launcher.js [resDir] [preview.png]
// Needs playwright + a Chromium (CHROME=/path/to/chrome or playwright's default browser).
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const RES = path.resolve(process.argv[2] || path.join(__dirname, '../../app/src/main/res'));
const PREVIEW = process.argv[3];
const BG = '#F2F5FC', NAVY = '#1F3A87', YELLOW = '#F5C33B';

// Mark geometry in public/icon.svg units (64x64). Glyph (pin top .. shadow bottom) = y 8.76..55.4.
const G_TOP = 4.86 + 5 * 0.78, G_BOT = 52.6 + 2.8, G_CY = (G_TOP + G_BOT) / 2, G_CX = 32;
const K = (0.761 * 72) / (G_BOT - G_TOP);          // dp per unit: glyph = 76.1% of the 72dp visible area (= Play icon)
const TX = +(54 - G_CX * K).toFixed(4), TY = +(54 - G_CY * K).toFixed(4), KS = +K.toFixed(5);

const PIN = 'M32,61C25.5,52.5 12.5,40.5 12.5,24.5a19.5,19.5 0,0 1,39 0C51.5,40.5 38.5,52.5 32,61z';
const HOUSE = 'M32,12.6L44.4,23.7h-3.9V35.2H23.5V23.7h-3.9z';
const DOOR = 'M30,27.4h4a1,1 0,0 1,1 1v5.8a1,1 0,0 1,-1 1h-4a1,1 0,0 1,-1 -1v-5.8a1,1 0,0 1,1 -1z';
const SHADOW = 'M21.5,52.6a10.5,2.8 0,1 0,21 0a10.5,2.8 0,1 0,-21 0z';

const FG_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets-src/launcher/render-launcher.js: 집핀 mark (public/icon.svg), adaptive foreground.
     108dp canvas, glyph ${(K * (G_BOT - G_TOP)).toFixed(1)}dp tall, centred: inside the 66dp safe-zone circle. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateX="${TX}" android:translateY="${TY}" android:scaleX="${KS}" android:scaleY="${KS}">
        <path android:fillColor="${YELLOW}" android:pathData="${SHADOW}" />
        <group android:translateX="7.04" android:translateY="4.86" android:scaleX="0.78" android:scaleY="0.78">
            <path android:fillColor="${NAVY}" android:pathData="${PIN}" />
            <path android:fillColor="#FFFFFF" android:strokeColor="#FFFFFF" android:strokeWidth="1.8"
                android:strokeLineJoin="round" android:pathData="${HOUSE}" />
            <path android:fillColor="${YELLOW}" android:pathData="${DOOR}" />
        </group>
    </group>
</vector>
`;

const ADAPTIVE_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets-src/launcher/render-launcher.js (matches the Play icon: #F2F5FC + navy mark). -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
`;
const BG_XML = `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">${BG}</color>
</resources>
`;

// Same content as SVG (for PNG rendering). Mirrors FG_XML exactly.
const fgSvgInner = `<g transform="translate(${TX} ${TY}) scale(${KS})"><path fill="${YELLOW}" d="${SHADOW}"/>` +
  `<g transform="translate(7.04 4.86) scale(.78)"><path fill="${NAVY}" d="${PIN}"/>` +
  `<path fill="#fff" stroke="#fff" stroke-width="1.8" stroke-linejoin="round" d="${HOUSE}"/><path fill="${YELLOW}" d="${DOOR}"/></g></g>`;
// Monochrome: assets-src/icon-monochrome.svg geometry (pin centred without the shadow), same scale as the foreground.
const monoSvgInner = `<defs><mask id="m" maskUnits="userSpaceOnUse" x="0" y="0" width="64" height="64">` +
  `<rect width="64" height="64" fill="#fff"/><path d="${HOUSE}" fill="#000" stroke="#000" stroke-width="1.8" stroke-linejoin="round"/>` +
  `<rect x="29" y="27.4" width="6" height="7.8" rx="1" fill="#fff"/></mask></defs>` +
  `<g transform="translate(${TX} ${TY}) scale(${KS})"><g transform="translate(0 1.5)"><g transform="translate(7.04 4.86) scale(.78)">` +
  `<path mask="url(#m)" d="${PIN}" fill="#fff"/></g></g></g>`;

const svg = (px, viewBox, inner) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="${viewBox}">${inner}</svg>`;
// Legacy = the 72dp visible part of the adaptive icon, under a rounded-square (as public/icon.svg, rx 14/64) or circle.
const legacy = (px, round) => svg(px, '18 18 72 72',
  (round ? `<circle cx="54" cy="54" r="36" fill="${BG}"/>` : `<rect x="18" y="18" width="72" height="72" rx="${(72 * 14 / 64).toFixed(2)}" fill="${BG}"/>`) + fgSvgInner);

const DENS = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

async function shot(page, markup, out) {
  await page.setContent(`<html><body style="margin:0;background:transparent">${markup}</body></html>`);
  await page.locator('svg').first().screenshot({ path: out, omitBackground: true });
}

(async () => {
  const exe = process.env.CHROME || ['/opt/pw-browsers/chromium-1194/chrome-linux/chrome'].find((p) => fs.existsSync(p));
  const br = await chromium.launch(exe ? { executablePath: exe, args: ['--no-sandbox'] } : { args: ['--no-sandbox'] });
  const page = await br.newPage({ deviceScaleFactor: 1 });
  const w = (rel, s) => { const f = path.join(RES, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, s); };
  w('values/ic_launcher_background.xml', BG_XML);
  w('drawable/ic_launcher_foreground.xml', FG_XML);
  w('mipmap-anydpi-v26/ic_launcher.xml', ADAPTIVE_XML);
  w('mipmap-anydpi-v26/ic_launcher_round.xml', ADAPTIVE_XML);
  for (const [d, s] of Object.entries(DENS)) {
    const dir = path.join(RES, 'mipmap-' + d); fs.mkdirSync(dir, { recursive: true });
    await shot(page, svg(108 * s, '0 0 108 108', monoSvgInner), path.join(dir, 'ic_launcher_monochrome.png'));
    await shot(page, legacy(48 * s, false), path.join(dir, 'ic_launcher.png'));
    await shot(page, legacy(48 * s, true), path.join(dir, 'ic_launcher_round.png'));
    fs.rmSync(path.join(dir, 'ic_maskable.png'), { force: true });
  }
  if (PREVIEW) await preview(page, PREVIEW);
  await br.close();
  console.log('launcher icons written to', RES);
})().catch((e) => { console.error(e); process.exit(1); });

// Preview sheet, rendered from the files actually written to RES (vector XML is converted back to SVG).
async function preview(page, out) {
  const xml = fs.readFileSync(path.join(RES, 'drawable/ic_launcher_foreground.xml'), 'utf8');
  const attr = (s, n) => (s.match(new RegExp('android:' + n + '="([^"]*)"')) || [])[1];
  const fg = xml.replace(/<\?xml[^>]*>|<!--[\s\S]*?-->|<vector[^>]*>|<\/vector>/g, '')
    .replace(/<group([^>]*)>/g, (_, a) => `<g transform="translate(${attr(a, 'translateX') || 0} ${attr(a, 'translateY') || 0}) scale(${attr(a, 'scaleX') || 1} ${attr(a, 'scaleY') || 1})">`)
    .replace(/<\/group>/g, '</g>')
    .replace(/<path([^>]*)\/>/g, (_, a) => `<path d="${attr(a, 'pathData')}" fill="${attr(a, 'fillColor') || 'none'}" stroke="${attr(a, 'strokeColor') || 'none'}" stroke-width="${attr(a, 'strokeWidth') || 0}" stroke-linejoin="${attr(a, 'strokeLineJoin') || 'miter'}"/>`);
  const bg = fs.readFileSync(path.join(RES, 'values/ic_launcher_background.xml'), 'utf8').match(/#[0-9A-Fa-f]{6}/)[0];
  const b64 = (rel) => 'data:image/png;base64,' + fs.readFileSync(path.join(RES, rel)).toString('base64');
  const mono = b64('mipmap-xxxhdpi/ic_launcher_monochrome.png');
  // Superellipse squircle (n=5) path in the 108 canvas, over the 72dp visible area.
  const sq = []; for (let i = 0; i < 360; i += 3) { const t = i * Math.PI / 180, c = Math.cos(t), s = Math.sin(t);
    sq.push(`${(54 + 36 * Math.sign(c) * Math.abs(c) ** 0.4).toFixed(2)},${(54 + 36 * Math.sign(s) * Math.abs(s) ** 0.4).toFixed(2)}`); }
  const masks = {
    circle: '<circle cx="54" cy="54" r="36"/>',
    squircle: `<polygon points="${sq.join(' ')}"/>`,
    'rounded square': '<rect x="18" y="18" width="72" height="72" rx="9"/>',
    teardrop: '<path d="M54,18h36v36a36,36 0 1 1 -36,-36z"/>',
  };
  const P = 168;
  const adaptive = (m, i) => svg(P, '18 18 72 72', `<defs><clipPath id="c${i}">${masks[m]}</clipPath></defs><g clip-path="url(#c${i})"><rect width="108" height="108" fill="${bg}"/>${fg}</g>`);
  const themed = (m, i, back, tint) => svg(P, '18 18 72 72', `<defs><clipPath id="t${i}">${masks[m]}</clipPath><mask id="tm${i}"><image href="${mono}" width="108" height="108"/></mask></defs>` +
    `<g clip-path="url(#t${i})"><rect width="108" height="108" fill="${back}"/><rect width="108" height="108" fill="${tint}" mask="url(#tm${i})"/></g>`);
  const layers = svg(P, '0 0 108 108', `<rect width="108" height="108" fill="${bg}"/>${fg}<rect x="18" y="18" width="72" height="72" fill="none" stroke="#c33" stroke-width=".5" stroke-dasharray="2 2"/>` +
    `<circle cx="54" cy="54" r="33" fill="none" stroke="#c33" stroke-width=".6"/><circle cx="54" cy="54" r="36" fill="none" stroke="#999" stroke-width=".4"/>`);
  const cell = (label, inner) => `<div class="c"><div class="i">${inner}</div><div class="l">${label}</div></div>`;
  const img = (rel, px) => `<img src="${b64(rel)}" width="${px}" height="${px}">`;
  const row = (title, cells, dark) => `<div class="r${dark ? ' d' : ''}"><h2>${title}</h2><div class="g">${cells.join('')}</div></div>`;
  const html = `<style>body{margin:0;font:13px system-ui,sans-serif;background:#fff;width:1180px}.r{padding:14px 20px}.d{background:#1b1d22;color:#ddd}
  h1{font-size:18px;margin:16px 20px 0}h2{font-size:13px;margin:0 0 8px;font-weight:600}.g{display:flex;gap:18px;flex-wrap:wrap;align-items:flex-end}
  .c{text-align:center}.l{margin-top:4px;color:#777;font-size:12px}.wall{background:linear-gradient(135deg,#7aa3c9,#c9b37a)}</style>
  <h1>집핀 launcher icon — background ${bg}, foreground = navy pin + house (Play icon v5 tint)</h1>
  ${row('Adaptive icon (Android 8+): launcher masks', [cell('full 108dp canvas<br>red = 66dp safe circle', layers), ...Object.keys(masks).map((m, i) => cell(m, adaptive(m, i)))])}
  <div class="r wall"><h2>On a wallpaper</h2><div class="g">${Object.keys(masks).map((m, i) => cell(m, adaptive(m, 10 + i))).join('')}</div></div>
  ${row('Themed icons (Android 13+, monochrome layer)', [cell('light', themed('circle', 20, '#D7E3FF', '#1A3A7A')), cell('light squircle', themed('squircle', 21, '#E3E8F5', '#253A6B')), cell('dark', themed('circle', 22, '#22304D', '#BFD0FF')), cell('dark squircle', themed('squircle', 23, '#2A3142', '#D0DAF5'))], false)}
  ${row('Legacy mipmaps (Android 7.x and below): ic_launcher / ic_launcher_round', [
    ...Object.entries(DENS).map(([d, s]) => cell(d + ' ' + 48 * s + 'px', img('mipmap-' + d + '/ic_launcher.png', 48 * s))),
    ...Object.entries(DENS).map(([d, s]) => cell('round ' + d, img('mipmap-' + d + '/ic_launcher_round.png', 48 * s)))])}
  ${row('Legacy at 48dp on dark', [cell('square xxxhdpi @2x', img('mipmap-xxxhdpi/ic_launcher.png', 96)), cell('round xxxhdpi @2x', img('mipmap-xxxhdpi/ic_launcher_round.png', 96)), cell('adaptive circle', adaptive('circle', 30).replace(`width="${P}" height="${P}"`, 'width="96" height="96"'))], true)}`;
  await page.setViewportSize({ width: 1180, height: 400 });
  await page.setContent(`<html><body>${html}</body></html>`);
  await page.screenshot({ path: out, fullPage: true });
  console.log('preview', out);
}
