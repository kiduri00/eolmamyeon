// Launcher icon (adaptive + legacy) for the 재개각 TWA — brand v7 (navy tile, white "각 잡힌" pin, navy house,
// yellow door + yellow dot). Geometry: ../brand-mark.js (same as brand_v7/logo/jaegaegak_mark_*.svg and the Play icon).
//
// Writes into <res> (default: ../../app/src/main/res):
//   values/ic_launcher_background.xml           #1F3A87 (brand navy, = Play icon / PWA maskable background)
//   drawable/ic_launcher_foreground.xml         vector, 108dp canvas, mark 44dp tall, centred; every ink point lies
//                                               inside the 66dp safe-zone circle (checked below, the script fails otherwise)
//   drawable/ic_launcher_monochrome.xml         vector, same geometry, single colour, house knocked out (Android 13 themed icons)
//   mipmap-anydpi-v26/ic_launcher.xml, ic_launcher_round.xml   adaptive icon (bg + fg + monochrome)
//   mipmap-{mdpi..xxxhdpi}/ic_launcher.png, ic_launcher_round.png   48dp legacy (Android 7.x), rounded square / circle;
//                                               mdpi/hdpi drop the dot and enlarge the pin (dot would be < 2px)
//   drawable-{mdpi..xxxhdpi}/ic_notification_icon.png   24dp white silhouette (house knocked out)
// and removes the old mipmap-*/ic_launcher_monochrome.png and ic_maskable.png (no longer referenced).
//
// Usage: NODE_PATH=$(npm root -g) node android/assets-src/launcher/render-launcher.js [resDir] [preview.png]
// Needs playwright + a Chromium (CHROME=/path/to/chrome or playwright's default browser).
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const M = require('../brand-mark');

const RES = path.resolve(process.argv[2] || path.join(__dirname, '../../app/src/main/res'));
const PREVIEW = process.argv[3];
const BG = M.NAVY, HOUSE = M.NAVY, WHITE = '#FFFFFF', YELLOW = M.YELLOW;

// ---- adaptive geometry (108dp canvas, 72dp visible, 66dp safe circle)
const GLYPH_DP = 44;                                   // mark ink height incl. dot = 61% of the 72dp visible area (Play icon: 60%)
const SAFE_R = 33;
const BH = M.BOX.y1 - M.BOX.y0, BCY = (M.BOX.y0 + M.BOX.y1) / 2;
const K = GLYPH_DP / BH;
const TX = +(54 - 32 * K).toFixed(4), TY = +(54 - BCY * K).toFixed(4), KS = +K.toFixed(5);
const reach = M.maxRadius(32, BCY) * K;               // farthest ink point from the canvas centre, in dp
if (reach > SAFE_R - 1) throw new Error(`foreground reaches ${reach.toFixed(2)}dp, outside the 66dp safe zone`);

const vec = (comment, body) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets-src/launcher/render-launcher.js: ${comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateX="${TX}" android:translateY="${TY}" android:scaleX="${KS}" android:scaleY="${KS}">
${body}
    </group>
</vector>
`;
const p = (fill, d, extra = '') => `        <path android:fillColor="${fill}"${extra} android:pathData="${d}" />`;
const FG_XML = vec(`재개각 mark, adaptive foreground. 108dp canvas, mark ${GLYPH_DP}dp tall,
     farthest ink point ${reach.toFixed(1)}dp from the centre (safe zone: 33dp radius).`,
  [p(WHITE, M.PIN), p(HOUSE, M.HOUSE), p(YELLOW, M.DOOR), p(YELLOW, M.DOT)].join('\n'));
const MONO_XML = vec('재개각 mark, monochrome layer (Android 13 themed icons): pin with the house knocked out, door, dot.',
  [p(WHITE, M.PIN + M.HOUSE, ' android:fillType="evenOdd"'), p(WHITE, M.DOOR), p(WHITE, M.DOT)].join('\n'));
const ADAPTIVE_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets-src/launcher/render-launcher.js (matches the Play icon: navy #1F3A87 + white 재개각 mark). -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;
const BG_XML = `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">${BG}</color>
</resources>
`;

// ---- SVG equivalents (PNG rendering + preview)
const markSvg = (tx, ty, ks, { pin = WHITE, house = HOUSE, door = YELLOW, dot = YELLOW, knock = false } = {}) =>
  `<g transform="translate(${tx} ${ty}) scale(${ks})">` +
  (knock ? `<path fill="${pin}" fill-rule="evenodd" d="${M.PIN}${M.HOUSE}"/>` : `<path fill="${pin}" d="${M.PIN}"/><path fill="${house}" d="${M.HOUSE}"/>`) +
  (door ? `<path fill="${door}" d="${M.DOOR}"/>` : '') + (dot ? `<path fill="${dot}" d="${M.DOT}"/>` : '') + '</g>';
const FG_SVG = markSvg(TX, TY, KS);
const MONO_SVG = markSvg(TX, TY, KS, { pin: '#fff', door: '#fff', dot: '#fff', knock: true });
const svg = (px, viewBox, inner) => `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="${viewBox}">${inner}</svg>`;

// Legacy = the 72dp visible part of the adaptive icon under a rounded square (r 22%) or a circle.
// Small densities: no dot, pin enlarged to the same visual weight.
const legacy = (px, round, small) => {
  let tx = TX, ty = TY, ks = KS, dot = YELLOW;
  if (small) {
    const b = M.BOX_NODOT, h = b.y1 - b.y0, k = (GLYPH_DP * 0.98) / h;
    ks = +k.toFixed(5); tx = +(54 - 32 * k).toFixed(4); ty = +(54 - ((b.y0 + b.y1) / 2) * k).toFixed(4); dot = null;
  }
  const shape = round ? `<circle cx="54" cy="54" r="36" fill="${BG}"/>` : `<rect x="18" y="18" width="72" height="72" rx="${(72 * 0.22).toFixed(2)}" fill="${BG}"/>`;
  return svg(px, '18 18 72 72', shape + markSvg(tx, ty, ks, { dot }));
};
// Notification: 24dp, white on transparent, pin with house knocked out, no door/dot (too small), 22dp tall.
const notif = (px) => {
  const b = M.BOX_NODOT, k = 22 / (b.y1 - b.y0);
  return svg(px, '0 0 24 24', markSvg(+(12 - 32 * k).toFixed(4), +(12 - ((b.y0 + b.y1) / 2) * k).toFixed(4), +k.toFixed(5),
    { pin: '#fff', door: null, dot: null, knock: true }));
};

const DENS = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
const SMALL = { mdpi: true, hdpi: true };

async function shot(page, markup, out) {
  await page.setContent(`<html><body style="margin:0;background:transparent">${markup}</body></html>`);
  await page.locator('svg').first().screenshot({ path: out, omitBackground: true });
}

(async () => {
  const exe = process.env.CHROME || ['/opt/pw-browsers/chromium-1194/chrome-linux/chrome'].find((q) => fs.existsSync(q));
  const br = await chromium.launch(exe ? { executablePath: exe, args: ['--no-sandbox'] } : { args: ['--no-sandbox'] });
  const page = await br.newPage({ deviceScaleFactor: 1 });
  const w = (rel, s) => { const fpath = path.join(RES, rel); fs.mkdirSync(path.dirname(fpath), { recursive: true }); fs.writeFileSync(fpath, s); };
  w('values/ic_launcher_background.xml', BG_XML);
  w('drawable/ic_launcher_foreground.xml', FG_XML);
  w('drawable/ic_launcher_monochrome.xml', MONO_XML);
  w('mipmap-anydpi-v26/ic_launcher.xml', ADAPTIVE_XML);
  w('mipmap-anydpi-v26/ic_launcher_round.xml', ADAPTIVE_XML);
  for (const [d, s] of Object.entries(DENS)) {
    const dir = path.join(RES, 'mipmap-' + d); fs.mkdirSync(dir, { recursive: true });
    await shot(page, legacy(48 * s, false, SMALL[d]), path.join(dir, 'ic_launcher.png'));
    await shot(page, legacy(48 * s, true, SMALL[d]), path.join(dir, 'ic_launcher_round.png'));
    fs.rmSync(path.join(dir, 'ic_launcher_monochrome.png'), { force: true });
    fs.rmSync(path.join(dir, 'ic_maskable.png'), { force: true });
    const nd = path.join(RES, 'drawable-' + d); fs.mkdirSync(nd, { recursive: true });
    await shot(page, notif(24 * s), path.join(nd, 'ic_notification_icon.png'));
  }
  if (PREVIEW) await preview(page, PREVIEW);
  await br.close();
  console.log(`launcher icons written to ${RES} (foreground reach ${reach.toFixed(2)}dp / safe 33dp)`);
})().catch((e) => { console.error(e); process.exit(1); });

async function preview(page, out) {
  const b64 = (rel) => 'data:image/png;base64,' + fs.readFileSync(path.join(RES, rel)).toString('base64');
  const sq = []; for (let i = 0; i < 360; i += 3) { const t = i * Math.PI / 180, c = Math.cos(t), s = Math.sin(t);
    sq.push(`${(54 + 36 * Math.sign(c) * Math.abs(c) ** 0.4).toFixed(2)},${(54 + 36 * Math.sign(s) * Math.abs(s) ** 0.4).toFixed(2)}`); }
  const masks = {
    circle: '<circle cx="54" cy="54" r="36"/>',
    squircle: `<polygon points="${sq.join(' ')}"/>`,
    'rounded square': '<rect x="18" y="18" width="72" height="72" rx="9"/>',
    teardrop: '<path d="M54,18h36v36a36,36 0 1 1 -36,-36z"/>',
  };
  const P = 168;
  const adaptive = (m, i) => svg(P, '18 18 72 72', `<defs><clipPath id="c${i}">${masks[m]}</clipPath></defs><g clip-path="url(#c${i})"><rect width="108" height="108" fill="${BG}"/>${FG_SVG}</g>`);
  const themed = (m, i, back, tint) => svg(P, '18 18 72 72', `<defs><clipPath id="t${i}">${masks[m]}</clipPath><mask id="tm${i}">${MONO_SVG}</mask></defs>` +
    `<g clip-path="url(#t${i})"><rect width="108" height="108" fill="${back}"/><rect width="108" height="108" fill="${tint}" mask="url(#tm${i})"/></g>`);
  const layers = svg(P, '0 0 108 108', `<rect width="108" height="108" fill="${BG}"/>${FG_SVG}<rect x="18" y="18" width="72" height="72" fill="none" stroke="#f66" stroke-width=".5" stroke-dasharray="2 2"/>` +
    `<circle cx="54" cy="54" r="33" fill="none" stroke="#f66" stroke-width=".6"/><circle cx="54" cy="54" r="36" fill="none" stroke="#bbb" stroke-width=".4"/>`);
  const cell = (label, inner) => `<div class="c"><div class="i">${inner}</div><div class="l">${label}</div></div>`;
  const img = (rel, px, pix) => `<img src="${b64(rel)}" width="${px}" height="${px}"${pix ? ' style="image-rendering:pixelated"' : ''}>`;
  const row = (title, cells, cls = '') => `<div class="r ${cls}"><h2>${title}</h2><div class="g">${cells.join('')}</div></div>`;
  const html = `<style>body{margin:0;font:13px system-ui,sans-serif;background:#fff;width:1180px}.r{padding:14px 20px}.d{background:#1b1d22;color:#ddd}
  h1{font-size:18px;margin:16px 20px 0}h2{font-size:13px;margin:0 0 8px;font-weight:600}.g{display:flex;gap:18px;flex-wrap:wrap;align-items:flex-end}
  .c{text-align:center}.l{margin-top:4px;color:#777;font-size:12px}.wall{background:linear-gradient(135deg,#7aa3c9,#c9b37a)}</style>
  <h1>재개각 launcher icon (brand v7) — background ${BG}, mark ${GLYPH_DP}dp, reach ${reach.toFixed(1)}dp of 33dp safe radius</h1>
  ${row('Adaptive icon (Android 8+): launcher masks', [cell('108dp canvas<br>red = 66dp safe circle', layers), ...Object.keys(masks).map((m, i) => cell(m, adaptive(m, i)))])}
  ${row('On a wallpaper', Object.keys(masks).map((m, i) => cell(m, adaptive(m, 10 + i))), 'wall')}
  ${row('Themed icons (Android 13+, monochrome layer)', [cell('light', themed('circle', 20, '#D7E3FF', '#1A3A7A')), cell('light squircle', themed('squircle', 21, '#E3E8F5', '#253A6B')), cell('dark', themed('circle', 22, '#22304D', '#BFD0FF')), cell('dark squircle', themed('squircle', 23, '#2A3142', '#D0DAF5'))])}
  ${row('Legacy mipmaps (Android 7.x): ic_launcher / ic_launcher_round', [
    ...Object.entries(DENS).map(([d, s]) => cell(d + ' ' + 48 * s + 'px', img('mipmap-' + d + '/ic_launcher.png', 48 * s))),
    ...Object.entries(DENS).map(([d, s]) => cell('round ' + d, img('mipmap-' + d + '/ic_launcher_round.png', 48 * s)))])}
  ${row('mdpi / hdpi zoomed (nearest) · notification icons on dark', [
    cell('mdpi x3', img('mipmap-mdpi/ic_launcher.png', 144, true)), cell('round mdpi x3', img('mipmap-mdpi/ic_launcher_round.png', 144, true)),
    cell('hdpi x2', img('mipmap-hdpi/ic_launcher.png', 144, true)),
    ...Object.entries(DENS).map(([d, s]) => cell('notif ' + d, img('drawable-' + d + '/ic_notification_icon.png', 24 * s)))], 'd')}`;
  await page.setViewportSize({ width: 1180, height: 400 });
  await page.setContent(`<html><body>${html}</body></html>`);
  await page.screenshot({ path: out, fullPage: true });
  console.log('preview', out);
}
